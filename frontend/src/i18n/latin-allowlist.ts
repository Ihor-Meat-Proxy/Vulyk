/** Strip `{placeholders}`, then yield Latin tokens (normalized). */
export function latinTokensInValue(value: string): string[] {
  const stripped = value.replace(/\{[^}]+\}/g, ' ')
  const raw = stripped.match(
    /[A-Za-z][A-Za-z0-9+._/-]*(?::[A-Za-z][A-Za-z0-9+._/-]*)*/g,
  )
  if (!raw) return []
  return raw.map((t) => t.replace(/[-.]+$/g, '').toLowerCase()).filter(Boolean)
}
